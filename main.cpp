//Дано дві змінні цілого типу A і B.
// Якщо їх значення не рівні, присвоїти кожній змінній суму цих значень.
// Якщо рівні, присвоїти змінним нульові значення.

void task_if10()
{
    int A, B, sum;

    cout << " Завдання If 10 " << endl;

    // Введення значень змінних A і B
    cout << "Введіть A і B: ";
    cin >> A >> B;

    if (!cin)
    {
        cout << "Неправильне ціле число!" << endl;
        return;
    }

    // Перевірка рівності значень змінних
    if (A != B)
    {
        // Знаходження суми початкових значень
        sum = A + B;

        // Присвоєння суми кожній змінній
        A = sum;
        B = sum;
    }
    else
    {
        // Якщо значення рівні, присвоюємо змінним нулі
        A = 0;
        B = 0;
    }

    // Виведення нових значень змінних
    cout << "Нове значення A = " << A << endl;
    cout << "Нове значення B = " << B << endl;
}


// Геометричне завдання. Варіант 26 (чорна область).
// Дано координати точки на площині та параметри фігури.
// Визначити, чи потрапляє точка в чорну область.

void task_geom26()
{
    double a, r; // половина сторони квадрата та радіус кола
    double x, y; // координати точки

    cout << "Геометрія 26 " << endl;

    // Введення параметрів фігури
    cout << "Введіть a і r: ";
    cin >> a >> r;

    if (!cin || a <= 0 || r <= 0 || r >= a)
    {
        cerr << "Некоректні дані!" << endl;
        return;
    }

    // Введення координат точки
    cout << "Введіть координати точки x, y: ";
    cin >> x >> y;

    if (!cin)
    {
        cout << "Не числові дані!" << endl;
        return;
    }

    // Знаходження квадрата відстані від точки до початку координат
    double distance = x * x + y * y;

    // Перевірка попадання точки у верхню праву чорну область
    bool black1 = x > 0 && y > x && y > 0 &&
                  x <= a && y <= a && distance > r * r;

    // Перевірка попадання точки у верхню ліву чорну область
    bool black2 = x < 0 && y > -x &&
                  x >= -a && y <= a && distance < r * r;

    // Перевірка належності точки до чорної області
    if (black1 || black2)
    {
        cout << "Точка належить чорній області." << endl;
    }
    else
    {
        cout << "Точка не належить чорній області." << endl;
    }

    return;
}
